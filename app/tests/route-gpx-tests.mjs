import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';
import {parseGPX} from '../js/gpx-parser.js';
import {validateActivityXML,MAX_TRACK_POINTS} from '../js/activity-limits.js';
globalThis.DOMParser=new JSDOM('').window.DOMParser;
const pt=(lon,ele='',extra='')=>`<rtept lat="20" lon="${lon}"><ele>${ele}</ele>${extra}</rtept>`;
const route=body=>`<gpx xmlns="http://www.topografix.com/GPX/1/1"><rte>${body}</rte></gpx>`;
const a=parseGPX(route(pt(-100)+pt(-99.999)),'ruta.gpx');
assert(a.distance>100&&a.distance<110);assert.equal(a.points.length,2);assert.equal(a.duration,null);assert.equal(a.ascent,null);assert(a.points.every(p=>p.speed===null));
const b=parseGPX(`<gpx><rte>${pt(-100,100)+pt(-99.999,110)}</rte><rte>${pt(-98,1000)+pt(-97.999,1000)}</rte></gpx>`,'dos.gpx');
assert(b.distance>200&&b.distance<220);assert(b.points[2].breakBefore);assert.notEqual(b.points[1].segmentId,b.points[2].segmentId);assert(b.ascent<100);
const broken=parseGPX(route(pt(-100)+pt('')+pt(-99.999)),'invalida.gpx');assert.equal(broken.distance,0);assert(broken.points[1].breakBefore);
const times=pt(-100,100,'<time>2026-10-21T12:00:00Z</time>')+pt(-99.999,110,'<time>2026-10-21T12:00:10Z</time>');
assert.equal(parseGPX(route(times),'horario.gpx').duration,10000);
const mixed=parseGPX(`<gpx><trk><trkseg>${pt(-100,100).replaceAll('rtept','trkpt')+pt(-99.999,110).replaceAll('rtept','trkpt')}</trkseg></trk><rte>${pt(-90)+pt(-89)}</rte></gpx>`,'mixta.gpx');assert.equal(mixed.points.length,2);assert(mixed.distance<110);
assert.throws(()=>parseGPX('<gpx><wpt lat="20" lon="-100"/></gpx>','waypoints.gpx'),/trkpt.*rtept/);
assert.throws(()=>validateActivityXML('<r:rtept/>'.repeat(MAX_TRACK_POINTS+1)),/50 000/);
assert.throws(()=>validateActivityXML('<trkpt/>'.repeat(MAX_TRACK_POINTS)+'<rtept/>'),/50 000/);
const serialized=JSON.stringify(a);assert(!serialized.includes('NaN'));
console.log('PASS GPX de ruta: rtept, namespaces, rutas separadas, huecos, horarios opcionales, preferencia de tracks y límite agregado de puntos.');
