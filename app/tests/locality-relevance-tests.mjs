import assert from 'node:assert/strict';
import {selectPosterLocalities,placeLocalityLabels,orderLocalityLabels} from '../js/locality-selection.js';
const points=[{lat:20,lon:-100,d:0,segmentId:0},{lat:20,lon:-99,d:104000,segmentId:0}];
const unknown=Array.from({length:80},(_,i)=>({name:'Lugar '+String.fromCharCode(65+Math.floor(i/26),65+i%26),lat:20,lon:-99.99+i*.012}));
const unsupported=selectPosterLocalities(points,unknown);
assert.deepEqual(unsupported.main,[]);
assert.deepEqual(unsupported.spares,[],'las sustitutas tampoco rellenan con importancia desconocida');
assert.equal(unsupported.rejected.filter(p=>p.reason==='sin-evidencia-de-relevancia').length,80);
const hamlets=unknown.map(p=>({...p,place:'hamlet'}));
const limited=selectPosterLocalities(points,hamlets);
assert(limited.main.length<=2,'los secundarios no llenan siete espacios por sí solos');
const major={name:'Principal',place:'town',lat:20,lon:-99.5};
assert(selectPosterLocalities(points,[...unknown,...hamlets,major]).main.some(p=>p.name==='Principal'));
const populations=[{name:'Población conocida',lat:20,lon:-99.5,population:1000},{name:'Sin población',lat:20,lon:-99.7},{name:'Muy pequeña',lat:20,lon:-99.9,population:20}];
assert.deepEqual(selectPosterLocalities(points,populations).main.map(p=>p.name),['Población conocida']);
const labels=orderLocalityLabels([{name:'Ciudad',priority:1,score:150},{name:'Extremo identificado',priority:0,score:55}],[{name:'Sustituta',score:200}]);
assert.deepEqual(labels.map(p=>p.name),['Extremo identificado','Ciudad','Sustituta']);
const candidates=Array.from({length:8},(_,i)=>({name:'Secundaria '+i,kind:'hamlet',index:i}));
const positions=candidates.map((_,i)=>({x:150+(i%3)*300,y:300+Math.floor(i/3)*200}));
assert.equal(placeLocalityLabels(candidates,positions,()=>100).placed.length,2,'el dibujo respeta el máximo incluso con sustitutas');
console.log('PASS relevancia: sin relleno desconocido, secundarios limitados, población acreditada y prioridad al dibujar.');
